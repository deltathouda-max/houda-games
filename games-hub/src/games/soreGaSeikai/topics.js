export const LETTERS = [
  'あ', 'か', 'さ', 'た', 'な', 'は', 'ま', 'や', 'ら', 'わ',
  'い', 'き', 'し', 'ち', 'に', 'ひ', 'み', 'り',
  'う', 'く', 'す', 'つ', 'ぬ', 'ふ', 'む', 'ゆ', 'る',
  'え', 'け', 'せ', 'て', 'ね', 'へ', 'め', 'れ',
  'お', 'こ', 'そ', 'と', 'の', 'ほ', 'も', 'よ', 'ろ',
]

// 「頭文字に縛られて無難な単語しか出てこない」状態を避けるため、
// 名詞カテゴリではなく一言ボケが自然と出てくる大喜利形式のお題にしてある。
// 回答はランダムな頭文字で始まる必要がある、という制約だけ従来通り残す。
export const THEMES = [
  '本当は嫌いだけど言えないもの',
  '言われたら地味にイラッとする一言',
  '絶対に人に言えない趣味',
  '上司に言われたら凹む一言',
  'デートで言われたら一気に冷めること',
  '実は経験がある恥ずかしい失敗',
  '100%嘘だとバレる言い訳',
  '転生したら絶対になりたくないもの',
  '面接で言ったら即不採用になる一言',
  '好きな人に言われたら舞い上がる一言',
  '絶対に流行らなそうな新商品',
  '老後の楽しみにしたいこと',
  '宝くじが当たったら真っ先にすること',
  '合コンで聞かれたら答えに困る質問',
  '上司が言いそうにない一言',
  '異世界に転生した時に持っていきたいもの',
  '実は密かに自慢できること',
  '深夜に急に思い出して後悔すること',
  '同窓会で聞かれたくない質問',
  '新しいクラスの校則にしたいこと',
  '絶対にバレたくない黒歴史',
  '結婚相手に求める意外な条件',
  '一日だけ許されるなら破ってみたいルール',
  '飲み会の一発芸として披露したいもの',
]

export function drawTopic() {
  const letter = LETTERS[Math.floor(Math.random() * LETTERS.length)]
  const theme = THEMES[Math.floor(Math.random() * THEMES.length)]
  return { letter, theme, text: `「${letter}」から始まる、${theme}は？` }
}
